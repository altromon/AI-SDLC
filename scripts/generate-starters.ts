import * as fs from 'fs';
import * as path from 'path';

const rootDir = path.resolve(__dirname, '..');

// 1. Generate starter-schemas.ts
function generateStarterSchemas(): void {
  const schemasDir = path.join(rootDir, 'schemas');
  const schemaFiles: string[] = [];

  function walk(dir: string): void {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const e of entries) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) {
        walk(full);
      } else if (e.name.endsWith('.schema.json') || (dir.endsWith('ide') && e.name.endsWith('.json'))) {
        schemaFiles.push(full);
      }
    }
  }
  walk(schemasDir);
  schemaFiles.sort();

  const entriesCode: string[] = [];
  const mapCode: string[] = [];

  for (const file of schemaFiles) {
    const rel = path.relative(rootDir, file).replace(/\\/g, '/');
    const content = fs.readFileSync(file, 'utf-8');
    const parsed = JSON.parse(content);
    const constName = 'SCHEMA_' + rel.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();

    entriesCode.push(`export const ${constName} = ${JSON.stringify(content)};`);
    mapCode.push(`  '${rel}': JSON.parse(${constName}),`);
  }

  const outputTs = `/**
 * AI-SDLC: Embedded Canonical JSON Schemas
 * Auto-generated by scripts/generate-starters.ts - DO NOT EDIT MANUALLY
 */

import type { JsonSchemaRule } from '../verifiers/schemas.js';

export interface StarterSchemaEntry {
  relPath: string;
  content: string;
  schema: JsonSchemaRule;
}

${entriesCode.join('\n\n')}

export const STARTER_SCHEMAS_MAP: Record<string, JsonSchemaRule> = {
${mapCode.join('\n')}
};

export const STARTER_SCHEMAS: StarterSchemaEntry[] = Object.entries(STARTER_SCHEMAS_MAP).map(([relPath, schema]) => ({
  relPath,
  schema,
  content: JSON.stringify(schema, null, 2),
}));
`;

  const destPath = path.join(rootDir, 'packages', 'core', 'src', 'init', 'starter-schemas.ts');
  fs.writeFileSync(destPath, outputTs, 'utf-8');
  console.log(`Generated ${destPath} with ${schemaFiles.length} schemas.`);
}

// 2. Generate starter-templates.ts
function generateStarterTemplates(): void {
  const templatesDir = path.join(rootDir, 'templates');
  const templateFiles: string[] = [];

  function walk(dir: string): void {
    const entries = fs.readdirSync(dir, { withFileTypes: true });
    for (const e of entries) {
      const full = path.join(dir, e.name);
      if (e.isDirectory()) {
        // Skip architecture templates since they are handled separately by architecture-templates.ts
        if (path.basename(full) === 'architecture' && path.dirname(full) === templatesDir) {
          continue;
        }
        walk(full);
      } else if (e.name.endsWith('.md') || e.name.endsWith('.yaml') || e.name.endsWith('.yml')) {
        templateFiles.push(full);
      }
    }
  }
  walk(templatesDir);
  templateFiles.sort();

  // Also include root .github/PULL_REQUEST_TEMPLATE.md and compliance/license-manifest.yaml
  const extraFiles: { fullPath: string; relPath: string }[] = [
    {
      fullPath: path.join(rootDir, '.github', 'PULL_REQUEST_TEMPLATE.md'),
      relPath: '.github/PULL_REQUEST_TEMPLATE.md',
    },
    {
      fullPath: path.join(rootDir, 'compliance', 'license-manifest.yaml'),
      relPath: 'compliance/license-manifest.yaml',
    },
  ];

  const entriesCode: string[] = [];
  const listItems: string[] = [];

  for (const file of templateFiles) {
    const rel = path.relative(rootDir, file).replace(/\\/g, '/');
    const content = fs.readFileSync(file, 'utf-8');
    const constName = 'STARTER_' + rel.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();

    entriesCode.push(`export const ${constName} = ${JSON.stringify(content)};`);
    listItems.push(`  { relPath: '${rel}', content: ${constName} },`);
  }

  for (const extra of extraFiles) {
    const content = fs.readFileSync(extra.fullPath, 'utf-8');
    const constName = 'STARTER_' + extra.relPath.replace(/[^a-zA-Z0-9]/g, '_').toUpperCase();
    entriesCode.push(`export const ${constName} = ${JSON.stringify(content)};`);
  }

  // Also add starter process/README.md
  const processReadmeContent = `# AI-SDLC: Process & Governance Framework

This directory hosts the deterministic governance, verification gates, and lifecycle protocols for AI-assisted software development.

## Core Protocols & Lifecycle
- **Phase 0 (Product Definition)**: \`specs/product/\` (Requirements \`FR-*\`, Use Cases \`UC-*\`, Actors \`ACT-*\`, Rules \`BR-*\`).
- **Phase 1 (System Architecture)**: \`templates/architecture/\` (arc42 + NAF v4, \`CMP-*\`, Decisions \`ADR-*\`).
- **Phase 2 (Cybersecurity Triad)**: \`templates/security/\` (Threat Actors \`ACT-THREAT-*\`, Abuse Cases \`ABUSE-*\`, Security Reqs \`SEC-REQ-*\`).
- **Phase 3 (Spec-Driven Delivery - SDD)**: \`specs/changes/active/<change-id>/\` (\`proposal.md\`, \`spec.md\`, \`design.md\`, \`tasks.md\`, \`handoff.yaml\`).
- **Phase 4 (Continuous Quality Gates & Verification)**:
  - Quality Gate: \`npx aisdlc verify quality\` (CC $\\le 10$, MI $\\ge 50$, LOC $\\le 40$)
  - BDD Testing: \`npx aisdlc verify testing\`
  - Traceability: \`npx aisdlc verify traceability\`
  - Licenses: \`npx aisdlc verify licenses\`
  - Schemas: \`npx aisdlc verify schemas\`
  - Release Gates: \`npx aisdlc check\` / \`npx aisdlc verify all\`
`;

  entriesCode.push(`export const STARTER_PROCESS_README = ${JSON.stringify(processReadmeContent)};`);
  listItems.push(`  { relPath: 'process/README.md', content: STARTER_PROCESS_README },`);
  listItems.push(`  { relPath: 'compliance/license-manifest.yaml', content: STARTER_COMPLIANCE_LICENSE_MANIFEST_YAML },`);

  const outputTs = `/**
 * AI-SDLC: Embedded Canonical Starter Templates
 * Auto-generated by scripts/generate-starters.ts - DO NOT EDIT MANUALLY
 */

export interface StarterTemplateEntry {
  relPath: string;
  content: string;
}

${entriesCode.join('\n\n')}

/**
 * Base non-architecture starter templates to scaffold on initProject.
 */
export const STARTER_BASE_TEMPLATES: StarterTemplateEntry[] = [
${listItems.join('\n')}
];
`;

  const destPath = path.join(rootDir, 'packages', 'core', 'src', 'init', 'starter-templates.ts');
  fs.writeFileSync(destPath, outputTs, 'utf-8');
  console.log(`Generated ${destPath} with ${templateFiles.length + extraFiles.length + 1} templates.`);
}

generateStarterSchemas();
generateStarterTemplates();
